-- ============================================================
-- エンドレスタワー：エンドレベル400以降の必要エンドEXPを一定にする（2026-08-04）
-- ------------------------------------------------------------
-- エンドポイントの段数解放はエンドレベル350（1ノード50段）で打ち止めなので、
-- そこから先も必要EXPが伸び続ける意味がない。
--   変更前: 必要EXP = 50 × エンドレベル（どこまでも増える）
--   変更後: 必要EXP = 50 × min(エンドレベル, 400)  ＝ LV400以降は 20,000 で一定
--
-- ・関数を差し替えるだけ。既存の tower_player.tower_exp（累計）はそのまま使え、
--   LV400以上のプレイヤーは自動的に繰り上がりが速くなる（データ移行は不要）。
-- ・エンドレベルの上限850、段数の解放段階（50/100/200/350）は変更なし。
-- ・supabase_tower.sql 本体にも同じ内容を反映済み。丸ごと流し直しても同じ結果になる。
-- ・apply_battle_result は触らないので、SQL適用順の鉄則には影響しない。
-- ============================================================

CREATE OR REPLACE FUNCTION tower_exp_to_next(p_lv int) RETURNS bigint
LANGUAGE sql IMMUTABLE AS $$ SELECT (50::bigint * LEAST(p_lv, 400)) $$;

