-- レイドボス HP +200万 (2026-07-22)
--   背景: 直近14日の平均討伐時間が約9.5分（出現枠30分）で、
--         後半に来たプレイヤーが戦えない問題への対応。
--   夜(21/22時): 700万 → 900万 / 昼(12〜17時): 400万 → 600万
--   HPは raid_slot_hp() に一元化されているため、この再定義だけで
--   次のスポーンから適用される（クライアント変更不要）。
-- ============================================================
CREATE OR REPLACE FUNCTION raid_slot_hp(p_slot int)
RETURNS int LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN p_slot IN (21, 22) THEN 9000000 ELSE 6000000 END
$$;
