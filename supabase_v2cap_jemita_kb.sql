### ステータス
- HP（生命）：0になると戦闘不能。
- MP（魔力）：スキルを使うと減る。残りが足りないスキルは不発になる。
- STR（腕力）：通常攻撃と物理スキルのダメージ。物理ダメージの軽減にも少しなる（VITの4分の1）。
- DEX（器用）：相手の回避率を押し下げて攻撃を当てる。さらにダメージの下振れを減らす。
- AGI（敏捷）：相手の攻撃を避ける。行動順を決め、相手より速いと確率で追加行動ができる。
- INT（知性）：魔法スキルのダメージ。魔法防御にもなる。HP・MPの回復量も決める。
- VIT（耐久）：物理ダメージを軽減する。魔法防御と回避にもわずかに影響。
- LUK（幸運）：相手より高いほどクリティカルが出る。クリティカルは威力が上がり、相手の防御の約1/3を無視する。回避にもわずかに乗る。

