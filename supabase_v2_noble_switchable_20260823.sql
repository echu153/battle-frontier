-- ============================================================
-- バトルフロンティアⅡ — ノーブルにも転職できるようにする（2026-08-23）
-- ------------------------------------------------------------
-- ★理由：v2のスキルは「LVアップのたびに抽選」で覚えるので、
--   開始時のノーブルでLV100に達するまでに取り逃したスキルは、
--   ノーブルへ戻れないため**二度と取れない**状態だった。
--   欲しければ転職して取り直せる形にする（条件は無し＝初期職と同じ扱い）。
--
-- サーバー側（v2_change_job）は tier='start' の職業を弾いているので、
-- ノーブルを初期職（basic）へ移すだけでよい。関数は触らない。
--
-- ※このSQLは何度流しても同じ結果になる（冪等）。
-- ============================================================

update public.v2_classes
   set tier = 'basic'
 where id = 'ノーブル';

-- 確認用：ノーブルが初期職の並びに入っていること
select id, tier, sort, req_jobs, req_proof
  from public.v2_classes
 where tier = 'basic'
 order by sort, id;
