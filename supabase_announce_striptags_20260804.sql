-- ============================================================
-- お知らせ本文から <b> タグを取り除く（2026-08-04）
-- ------------------------------------------------------------
-- お知らせは HTML を描画せず、そのままの文字として表示される
-- （Game.jsx が {a.content} を whiteSpace:'pre-wrap' で出しているだけ）。
-- そのため <b> がそのまま画面に出てしまっていた。
-- 既に配信済みの行から取り除く。タグを消すだけなので本文は変わらない。
--
-- ⚠お知らせにHTMLタグは使わない。強調したいときは「」や■で表現する。
-- ============================================================

UPDATE announcements
   SET content = replace(replace(content, '<b>', ''), '</b>', '')
 WHERE content LIKE '%<b>%';

