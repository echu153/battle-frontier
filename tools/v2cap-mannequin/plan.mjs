// ChatGPT（GPT Image）に頼む文。1枚目＝マネキンのシート・2枚目＝待機の1コマ目
export const promptOf = (cls, g, kind) => {
  const fam = FAMILY[familyOf(cls, g, kind)]
  const gear = gearOf(cls, g)
  const fx = KIND_FX[kind] || gear.fx
  const sex = g === 'm' ? '男性' : '女性'
  return [
    `1枚目はマネキン（木のデッサン人形）の動きの手本、2枚目はドット絵のキャラクター（${cls}・${sex}）です。`,
    `2枚目のキャラクターが、1枚目のマネキンと同じ動き（${fam.label}）をする6コマを、横一列に並べた1枚の画像で作って。`,
    '・ポーズ（体の傾き・手足の角度・踏み込みの大きさ・武器の向き）は、6コマとも1枚目のマネキンに合わせる',
    `・${fam.hint}`,
    '・マネキンの見た目（木の人形・灰色の板）は描かない。描くのは2枚目のキャラクターだけ',
    '・キャラクターの色・服・髪型・頭身・大きさ・体の向き（斜め前）は2枚目と同じ。ドット絵のまま（ぼかし・なめらかな線にしない）',
    fam.armed
      ? `・持ち物は2枚目と同じ（${gear.w}）。マネキンの${fam.armed}は、この持ち物に置きかえる。6コマ全部で同じ持ち物・同じ手。増やさない・消さない・別の武器を描き足さない`
      : `・マネキンは素手だが、キャラクターは2枚目の持ち物（${gear.w}）を持ったまま同じ動きをする。6コマ全部で同じ持ち物・同じ手。増やさない・消さない・別の武器を描き足さない`,
    '・投げる瓶や札・撃つ弾・魔法の光は、手もとから出してよい',
    `・効果（${fx}）は小さく、キャラのすぐまわりだけ`,
    '・6コマの並び・間隔・足もとの高さ・立ち位置は1枚目と同じ。右を向いたまま',
    '・コマの間は1枚目と同じく広く空ける。武器・効果・マント・髪が隣のコマにかからないように',
    '・背景は真緑（#00FF00）の一色。文字・番号・枠線・地面・影は入れない',
  ].join('\n')
}
