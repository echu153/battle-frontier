// 回復で小瓶を使うクラス（ほかは祈る）
const POTION_HEAL = new Set(['薬師', 'アルケミスト', '霊薬師'])
const bare = (w) => /素手|無い/.test(w)

// 種類ごとの動き（③④⑤と効果）。物理と魔法はクラスのふだんの攻撃を「技らしく大きく」したもの・補助と回復は前へ出ない
export const kindMotionOf = (cls, g, kind) => {
  const gear = gearOf(cls, g)
  const hold = bare(gear.w) ? '素手のまま' : `${gear.w}を持ったまま`
  if (kind === 'buff') return { a: `${hold}身構えて、体に力をためる`, b: '胸を張って力を解き放つ（体から光が立ちのぼる・前へは出ない）', c: '光が消えかけ、構えを解きかける', fx: '体のまわりに立ちのぼるオーラ' }
  if (kind === 'heal') return POTION_HEAL.has(cls)
    ? { a: '小瓶を頭の上へかかげる', b: '小瓶を傾けて自分に薬をふりかける（前へは出ない）', c: '小瓶を下ろしかける', fx: 'きらきらした緑のしずく' }
    : { a: `${hold}胸の前で祈る`, b: '顔を上げて、頭の上から降りそそぐ光を受ける（前へは出ない）', c: '祈りを解きかける', fx: 'やわらかい緑と白の光' }
  const m = OTHER_KIND[`${cls}-${kind}`] || gear
  return { a: `${m.a}（ふだんの攻撃より大きく、力をためる）`, b: `${m.b}（ふだんの攻撃より大きく力強い動き）`, c: m.c, fx: m.fx }
}

