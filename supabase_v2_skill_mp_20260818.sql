-- バトルフロンティアⅡ（v2）— 上位職スキルの倍率調整にともなう消費MPの更新
-- 2026-08-18
-- ------------------------------------------------------------
-- 上位職の切り札の倍率をあるけみすと水準（合計 物理2.4／魔法2.7）まで下げたので、
-- 威力が横並びになった切り札のうち**MPだけ高いまま残っていた6個**を22に揃える。
-- （そのままだと「同じ威力・同じ発動率でMPだけ高い＝誰も編成しない技」になるため。
--   v2のスキルは習得済みで職業をまたいで持ち越せるので、この状態は本当に死に技になる）
--
-- ★消費MPは skills.js と v2_skills の2か所にある（サーバーが編成の想定利用MPを検証するため）。
--   JS側は済み。このSQLはDB側の同期。supabase_v2_core.sql の種も同じ値に直してあるので、
--   全文を流し直しても同じ結果になる（on conflict do update set mp = excluded.mp）。
--
-- ⚠これはv2の表だけを触る。旧版のテーブル・関数には一切影響しない。
-- ⚠既に保存済みの編成（v2_profiles.skill_set）は想定利用MPが**下がる**方向なので、
--   最大MPを超えて保存不能になることはない。作り直しは不要。
-- ============================================================

update public.v2_skills set mp = 22 where name in (
  '月影',              -- 侍       24 → 22
  'メテオストライク',  -- 賢者     26 → 22
  'ジャックポット',    -- ギャンブラー 24 → 22
  '天墜竜閃',          -- 竜騎士   28 → 22
  '禁術・神降ろし',    -- 式神使い 24 → 22
  'やっちゃえ！'       -- ブリーダー 26 → 22
);

-- 確認（6行・すべて mp = 22 になっていればOK）
select name, cls, mp from public.v2_skills
where name in ('月影','メテオストライク','ジャックポット','天墜竜閃','禁術・神降ろし','やっちゃえ！')
order by cls, name;
