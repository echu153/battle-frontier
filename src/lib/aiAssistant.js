// 入力正規化：全角→半角、空白・記号・助詞ノイズを除去し、ひらがな小文字化に近い形へ
const normalize = (s) => (s || '')
  .toString()
  .toLowerCase()
  .replace(/[Ａ-Ｚａ-ｚ０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xFEE0))
  .replace(/\s+/g, '')
  .replace(/[、。，．・！!？?「」『』（）()【】_~〜:：-]/g, '')

