// ===== 場所ごとの顔ぶれ =====
// 【確定】通常は表の上から2体ずつ①②③。②には①の敵・③には②の敵も出る（1つ前の場所の敵だけ）。
//         時間帯の6体とレア5体は①②③すべて。ボスは場所ごと（2026-10-09 ユーザー決定）
export const rosterOf = (areaNo, sub) => {
  const a = AREA_ROSTERS[areaNo - 1]
  const n = a.normals
  return {
    enemies: sub === 1 ? n.slice(0, 2) : sub === 2 ? n.slice(0, 4) : n.slice(2, 6),
    timed: a.timed,
    rares: a.rares,
    boss: a.bosses[sub - 1],
  }
}
// 場所のid（1〜45）→ { enemies, timed, rares, boss }
export const ROSTERS = Object.fromEntries(AREA_ROSTERS.flatMap((_, k) => [1, 2, 3].map(sub => [k * 3 + sub, rosterOf(k + 1, sub)])))
