// 場面 kind のセリフを1つ選ぶ。last＝直前のセリフの文（同じものが続かないように・2つ以上あるときだけ）
export const linesOf = (kind) => OWL_LINES[kind] || OWL_LINES.tap
export const pickLine = (kind, { rng = Math.random, last = null } = {}) => {
  const list = linesOf(kind)
  const pool = list.length > 1 && last ? list.filter(l => fillLine(l.text) !== last) : list
  const from = pool.length ? pool : list
  const l = from[Math.min(from.length - 1, Math.floor(rng() * from.length))]
  return { face: l.face || OWL_FACE_KEYS[0], text: fillLine(l.text) }
}

// 博物館を開いたときの場面。donated＝寄贈した数（登録の記録の行の数・読み込む前と読めなかったときは null）・donatable＝いま寄贈できる装備の数。
// はじめて（まだ1つも寄贈していない）＝名乗る → 寄贈できる装備がない → 夜おそく → ふつう の順に見る
export const enterKindOf = ({ donated = null, donatable = null, at = new Date() } = {}) => {
  if (donated === 0) return 'intro'
  if (donated !== null && donatable === 0) return 'enterEmpty'
  return isNight(at) ? 'enterNight' : 'enter'
}

// 寄贈の結果の場面。items＝寄贈した装備（{ tier }＝lib/museum.js の段階）・rewards＝新しくもらった報酬（サーバーの { key }）。
// エリアがそろった → 報酬がもらえた → とてもよく鍛えた品（+9）がある → まとめて寄贈 → よく鍛えた品（+5） → ふつう の順に見る。
// 1つも寄贈できなかった（一括で全部飛ばされた）ときは、うまくいかなかったときと同じ
export const donateKindOf = (items = [], rewards = []) => {
  const keys = (rewards || []).map(w => String(w?.key || ''))
  const tiers = (items || []).map(x => Number(x?.tier))
  if (!tiers.length) return 'error'
  if (keys.some(k => k.startsWith('area:'))) return 'donateComplete'
  if (keys.length) return 'donateSet'
  if (tiers.includes(tierOfPlus(9))) return 'donateGreat'
  if (tiers.length > 1) return 'donateMany'
  if (tiers.includes(tierOfPlus(5))) return 'donateGood'
  return 'donate'
}

