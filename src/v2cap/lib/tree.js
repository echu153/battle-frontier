// 運勢の倍率（10分率の整数。サーバーも整数で持つ）
export const multTenthsOf = (f) => Math.round((f?.mult ?? 1) * 10)
// その運勢でもらえるEXP＝推奨の場所で10回出撃したくらい × 運勢の倍率。切り上げは整数で：(基準 × 倍率10分率 + 9) ÷ 10（サーバーと同じ）
export const prayExpOf = (lv, f) => Math.floor((tenSortieExpOf(Math.max(1, lv || 1)) * multTenthsOf(f) + 9) / 10)
