export const NG_JA = /(セックス|せっくす|エロ|アダルト|童貞|処女|射精|挿入|オナニー|自慰|まんこ|マンコ|ちんこ|チンコ|ちんぽ|チンポ|ペニス|性器|レイプ|強姦|ヌード|全裸|風俗|ポルノ|18禁|性行為|グロ画像|グロ動画|内臓|死体|惨殺|バラバラ死体|リョナ|死ね|殺すぞ|ぶっ殺|きちがい|キチガイ|気違い|池沼|知障|くたばれ)/
export const NG_EN = /\b(sex\w*|adult|porn\w*|fuck\w*|r-?18)\b/

export const isJemitaNG = (s) => {
  const base = String(s || '').normalize('NFKC').replace(/[\u200B-\u200D\uFEFF]/g, '').toLowerCase()
  if (NG_JA.test(base.replace(/[\s.\-_、。・,]/g, ''))) return true
  return NG_EN.test(base.replace(/\b([a-z])[\s.\-_、。・,]+(?=[a-z]\b)/g, '$1'))
}
