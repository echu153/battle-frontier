  const orb = o && oa ? { src: srcOf(key, illustFxKindOf('idle', 'orb')), at: o.at, size: o.size, h: oa.h / oa.w } : null
  const dust = def.idle.slam?.dust || null
  // 遭遇のイラストはドット絵版と同じ
