// 【確定】2026-10-30 HPの節目のバフの絵（def.buffs・黒龍・ユーザー「バフかけたときのエフェクトやイラストも用意しておきたい グラブル意識」）：
//   節目を切った瞬間に部品の立ち絵からバフのポーズの絵へ切り替え（BUFF_IN_MS）、オーラを出す（BUFF_AURA_IN_MS）：後ろの闘気は小さく出て広がり、
//   手前の殻は大きく出て竜へ閉じる（どちらも少し行きすぎてから戻る）。
