const easeOutBack = (k) => 1 + 2.70158 * (k - 1) ** 3 + 1.70158 * (k - 1) ** 2
// 見せる長さはバフごと（show.holdMs・無ければ BUFF_HOLD_MS）
export const buffHoldOf = (b) => b?.show?.holdMs ?? BUFF_HOLD_MS
export const buffArtMsOf = (b) => buffHoldOf(b) + Math.max(BUFF_OUT_MS, BUFF_AURA_OUT_MS)
export const illustBuffShowAt = (art, name, ms) => {
  const b = art?.buffs?.[name]
  const hold = buffHoldOf(b)
  if (!b || !(ms >= 0) || ms >= buffArtMsOf(b)) return null
  const kIn = Math.min(1, ms / BUFF_IN_MS), kOut = Math.min(1, Math.max(0, ms - hold) / BUFF_OUT_MS)
  const back = ms >= hold
  const pose = !b.pose ? 0 : back ? 1 - smooth(Math.max(0, 2 * kOut - 1)) : smooth(Math.min(1, 2 * kIn))
  const rig = !b.pose ? 1 : back ? smooth(Math.min(1, 2 * kOut)) : 1 - smooth(Math.max(0, 2 * kIn - 1))
  const aIn = Math.min(1, ms / BUFF_AURA_IN_MS), aOut = Math.min(1, Math.max(0, ms - hold) / BUFF_AURA_OUT_MS)
  const from = b.front ? 1.22 : 0.78
  // flicker＝見せているあいだオーラが揺らめく（逆鱗の闘気・大きさが速く小さく揺れる）
  const fl = b.show?.flicker ? 1 + b.show.flicker * Math.sin(ms / 45) * (1 - aOut) * Math.min(1, ms / BUFF_AURA_IN_MS) : 1
  const aura = b.aura ? { op: smooth(aIn) * (1 - smooth(aOut)), scale: (from + (1 - from) * easeOutBack(aIn) + 0.08 * aOut) * fl } : null
  const flash = ms < BUFF_FLASH_MS ? (1 - ms / BUFF_FLASH_MS) ** 2 : 0
  return { rig, pose, aura, flash }
}
// 決まった乱れ（0〜1・同じ i と salt なら同じ値）＝火の粉の場所や速さ
const hash01 = (i, salt) => { const x = Math.sin(i * 127.1 + salt * 311.7) * 43758.5453; return x - Math.floor(x) }
// 足元から立ちのぼる火の粉1つ（t＝0〜1 の進み・i＝何番目）：左右に少し揺れ、上で小さく薄くなる
const sparkAt = (p, i, t) => {
  const x0 = p.x[0] + (p.x[1] - p.x[0]) * hash01(i, 3)
  return { x: x0 + Math.sin(t * 6 + i) * 10, y: p.y - (p.rise || 380) * (1 - (1 - t) ** 2) * (0.55 + 0.45 * hash01(i, 4)),
    r: (2.5 + 3 * hash01(i, 5)) * (1 - 0.5 * t) * (p.size || 1), op: (t < 0.15 ? t / 0.15 : 1) * (1 - t) }
}
// 【確定】2026-10-30 舞台に降る雨（def.buffs の show.rain・after.rain・ユーザー「篠突く雨後は常に雨降るモーション追加していいかも」）：
//   r＝{ n（本数）, fallMs（上から下まで落ちる時間）, len（筋の長さ・舞台の高さの割合）, slant（落ちるあいだに横へずれる割合・負＝左へ）, splash（足元の水の輪の数） }・tMs＝時計 →
//   { far, near（奥の細い筋と手前の太い筋：[x（幅の割合）, y（高さの割合・筋の上のはし）, len]）, splashes: [{ x, y, t（0〜1・広がる進み） }] }。
//   手前の筋は速く長い。水の輪は1回ごとに場所が変わる
const BOLT_MS = 210
export const buffRainAt = (r, tMs) => {
  const far = [], near = []
  for (let i = 0; i < r.n; i++) {
    const isNear = hash01(i, 21) < 0.4
    const t = (tMs / (r.fallMs * (isNear ? 0.8 : 1.15) * (0.9 + 0.2 * hash01(i, 22))) + hash01(i, 23)) % 1
    const len = r.len * (isNear ? 1.25 : 0.8) * (0.75 + 0.5 * hash01(i, 24))
    ;(isNear ? near : far).push([-0.02 + 1.14 * hash01(i, 25), -len + (1 + len) * t, len])
  }
  const splashes = []
  for (let i = 0; i < (r.splash || 0); i++) {
    const u = tMs / (420 + 380 * hash01(i, 26)) + hash01(i, 27), turn = Math.floor(u)
    splashes.push({ x: hash01(i + turn * 13, 28), y: 0.92 + 0.07 * hash01(i + turn * 13, 29), t: u - turn })
  }
  return { far, near, splashes }
}
// 【確定】2026-10-30 付いた瞬間の強い見せ方（def.buffs の show・ユーザー「逆鱗のモーションがパッとしない、もうちょっと強化感を出してほしい」）：
//   b＝bossIllustOf の buffs の1つ・ms＝付いてからのミリ秒 → { dim, dimColor（舞台を暗くする濃さと色）, shake: [x, y]（舞台の揺れ px）, punch（ポーズの絵のふくらみ・1＝そのまま）,
//   rings: [{ x, y, r, op, w }]（口から広がる衝撃の輪）, sparks: [{ x, y, r, op }]（足元から噴き上がる火の粉）, ringColor, sparkColor, ringCore, sparkCore（芯の色）,
//   bolts: [{ pts, op }]（手へ落ちる稲妻）, boltColor, flash（舞台ぜんぶが光る 0〜1）, rain（土砂降り・buffRainAt に渡す決まり＋ k（濃さ）・t（時計））}（立ち絵の px）か null（show が無い・終わった）
//   揺れは吠えた瞬間がいちばん強く、見せているあいだに弱まる。ふくらみはすぐに punch まで→少し戻る。暗さは見せ終わると戻る
export const buffSceneAt = (b, ms) => {
  const s = b?.show
  if (!s || !(ms >= 0)) return null
  const hold = buffHoldOf(b)
  if (ms >= hold + BUFF_AURA_OUT_MS) return null
  const fadeOut = 1 - smooth(Math.min(1, Math.max(0, ms - hold) / BUFF_AURA_OUT_MS))
  const dim = (s.dim || 0) * Math.min(1, ms / 180) * fadeOut
  const amp = (s.shake || 0) * Math.max(0, 1 - ms / hold) ** 1.5
  const shake = [amp * Math.sin(ms / 23), amp * 0.6 * Math.sin(ms / 31 + 1.3)]
  const punch = s.punch ? 1 + s.punch * (ms < 160 ? smooth(ms / 160) : 1 - 0.45 * smooth(Math.min(1, (ms - 160) / 400))) * fadeOut : 1
  const rings = []
  if (s.rings) for (let i = 0; i < s.rings.n; i++) {
    const t = (ms - 80 - i * s.rings.everyMs) / (s.rings.durMs || 700)
    if (t <= 0 || t >= 1) continue
    rings.push({ x: s.rings.at[0], y: s.rings.at[1], r: 30 + (s.rings.maxR || 420) * (1 - (1 - t) ** 2), op: (1 - t) ** 1.2, w: 14 * (1 - t) + 2, flat: s.rings.flat })
  }
  const sparks = []
  if (s.burst) for (let i = 0; i < s.burst.n; i++) {
    const t = (ms - hash01(i, 1) * 500) / (900 + hash01(i, 2) * 700)
    if (t > 0 && t < 1) sparks.push(sparkAt(s.burst, i, t))
  }
  // 稲妻：落ちた瞬間にいちばん明るく、すぐ消える。形は 50ms ごとに変わる（ちらつく）
  const bolts = []
  let flash = 0
  for (const [i, b] of (s.bolts || []).entries()) {
    const t = (ms - b.at) / BOLT_MS
    if (t < 0 || t >= 1) continue
    const seed = Math.floor(ms / 50) + i * 31
    bolts.push({ op: (1 - t) ** 0.7, pts: Array.from({ length: 8 }, (_, j) => {
      const u = j / 7, off = j === 7 ? 0 : (hash01(j, seed) - 0.5) * 80
      return [b.from[0] + (b.to[0] - b.from[0]) * u + off, b.from[1] + (b.to[1] - b.from[1]) * u + off * 0.2]
    }) })
    if (b.flash) flash = Math.max(flash, b.flash * (1 - t) ** 2)
  }
  return { dim, dimColor: s.dimColor || null, shake, punch, rings, sparks, ringColor: s.rings?.color || null, sparkColor: s.burst?.color || null,
    ringCore: s.rings?.core || null, sparkCore: s.burst?.core || null, bolts, boltColor: s.boltColor || null, flash,
    rain: s.rain ? { ...s.rain, k: Math.min(1, ms / 140) * fadeOut, t: ms } : null }
}
// 開戦の動きの見せ方（衝撃の輪・揺れ・暗さ・光の粒・稲妻）：motion＝bossIllustOf の intro・ms＝流しはじめてからのミリ秒。
//   shows の1つずつを at から buffSceneAt と同じ形で作って重ねる（揺れは足す・暗さは濃いほう・輪と粒と稲妻は全部）。出ているものが無ければ null（intro の無い動きも）
export const introSceneAt = (motion, ms) => {
  const list = (motion?.shows || []).map(s => buffSceneAt({ show: s }, ms - s.at)).filter(Boolean)
  if (!list.length) return null
  const out = { ...list[0], shake: [...list[0].shake], rings: [...list[0].rings], sparks: [...list[0].sparks], bolts: [...list[0].bolts] }
  for (const c of list.slice(1)) {
    out.shake[0] += c.shake[0]
    out.shake[1] += c.shake[1]
    out.punch *= c.punch
    out.rings.push(...c.rings)
    out.sparks.push(...c.sparks)
    out.bolts.push(...c.bolts)
    if (c.dim > out.dim) { out.dim = c.dim; out.dimColor = c.dimColor }
    out.flash = Math.max(out.flash, c.flash)
    for (const f of ['ringColor', 'sparkColor', 'ringCore', 'sparkCore', 'boltColor']) out[f] ||= c[f]
  }
  return out
}
// 待機の光（def.idle.lights・ゼルギアスの炉心と肩の玉）：いまの濃さつき。min〜max を periodMs で脈打つ（phase＝ずらし 0〜1）。tMs＝待機の時計
export const rigLightsAt = (lights, tMs) => lights.map(l => ({ ...l, op: l.min + (l.max - l.min) * (0.5 + 0.5 * Math.sin(2 * Math.PI * (tMs / l.periodMs + (l.phase || 0)))) }))
// 開戦の動きの絵ぜんたいの登場（motion.enter＝[ミリ秒, { s（大きさ）, sy（縦の縮み）, x, y（ずれ・枠の割合）, bright（明るさ）, op（濃さ）, glow（体のまわりの光 0〜1） }, 区間の速さ]）。
//   書いていない値はふつうの形（s 1・sy 1・x 0・y 0・bright 1・op 1・glow 0）。流し終わったら null（ふつうの形に戻っている＝最後のキーは {}）
const ENTER_ZERO = { s: 1, sy: 1, x: 0, y: 0, bright: 1, op: 1, glow: 0 }
export const introEnterAt = (motion, ms) => {
  const e = motion?.enter
  if (!e || ms >= e.at(-1)[0]) return null
  if (ms <= e[0][0]) return { ...ENTER_ZERO, ...e[0][1] }
  let i = 0
  while (i < e.length - 2 && ms >= e[i + 1][0]) i++
  const [t0, p0] = e[i], [t1, p1, ease] = e[i + 1]
  const k = (EASES[ease] || smooth)((ms - t0) / (t1 - t0))
  return Object.fromEntries(Object.keys(ENTER_ZERO).map(f => [f, (p0[f] ?? ENTER_ZERO[f]) + ((p1[f] ?? ENTER_ZERO[f]) - (p0[f] ?? ENTER_ZERO[f])) * k]))
}
// 開戦の動きの光の柱（motion.beam＝{ fromMs, toMs, inMs, outMs, op, w（枠の高さに対する幅）, color }）：いまの濃さつき。出ていなければ null
export const introBeamAt = (motion, ms) => {
  const b = motion?.beam
  if (!b || ms < b.fromMs || ms >= b.toMs) return null
  return { w: b.w, color: b.color, op: b.op * Math.min(1, (ms - b.fromMs) / b.inMs) * Math.min(1, (b.toMs - ms) / b.outMs) }
}
// 【確定】2026-10-30 付いているあいだの見た目（def.buffs の after・ユーザー「逆鱗後はモーションも変更していい」）：
//   list＝付いているバフ [{ b（bossIllustOf の buffs の1つ）, since（付いてからのミリ秒・印が片付いたあとは Infinity） }]・tMs＝いまのミリ秒 →
//   { glow（体が赤く脈打つ強さ 0〜1）, glowColor, sparks（足元から絶えず立ちのぼる火の粉）, sparkColor, sparkCore, tempo（待機の速さ）, dim, dimColor（舞台の暗さ）,
//   rain（降り続ける雨・buffRainAt に渡す決まり＋ k（濃さ）・t（時計）か null）, flame（竜の後ろで燃え続けるオーラ：{ p（絵）, amp（揺らぎ）, op（濃さ） } か null）, pulse（体の中の光のゆらぎ 0〜1） } か null（after のあるバフが無い）
//   脈と火の粉は見せ終わるころから 0.6秒で出てくる（オーラは付いた瞬間のオーラが消えはじめる少し前から 0.5秒で）。待機の速さはポーズの絵を出して部品の立ち絵が隠れたあと（BUFF_IN_MS）に切り替える
//   （速さを変えた瞬間に待機の動きが飛ぶのを隠す）
export const buffAfterAt = (list, tMs) => {
  const on = list.filter(x => x.b?.after)
  if (!on.length) return null
  const out = { glow: 0, glowColor: null, sparks: [], sparkColor: null, sparkCore: null, tempo: 1, dim: 0, dimColor: null, rain: null, flame: null, pulse: 0 }
  for (const { b, since } of on) {
    const a = b.after, k = smooth(Math.min(1, Math.max(0, since - buffHoldOf(b)) / 600))
    if (since >= BUFF_IN_MS && a.tempo) out.tempo = Math.max(out.tempo, a.tempo)
    if (a.flame && b.aura) {
      const fk = smooth(Math.min(1, Math.max(0, since - buffHoldOf(b) + 200) / 500))
      if (fk > 0) {
        out.flame = { p: b.aura, amp: a.flame.amp, op: a.flame.op * fk }
        // ゆっくりした波＋細かいゆらぎ（60ミリ秒ごと）
        out.pulse = fk * (0.5 + 0.3 * Math.sin(tMs / 230) + 0.2 * (hash01(Math.floor(tMs / 60), 42) * 2 - 1))
      }
    }
    if (a.glow && k > 0) {
      // 心臓のように2回ずつ（強く・弱く）
      const u = (tMs % a.glow.periodMs) / a.glow.periodMs
      const beat = Math.exp(-(((u - 0.1) / 0.06) ** 2)) + 0.65 * Math.exp(-(((u - 0.3) / 0.07) ** 2))
      out.glow = Math.max(out.glow, k * Math.min(1, beat))
      out.glowColor = a.glow.color
    }
    if (a.embers && k > 0) {
      for (let i = 0; i < a.embers.n; i++) {
        const life = 1600 + hash01(i, 6) * 900, t = ((tMs + hash01(i, 7) * life) % life) / life
        const sp = sparkAt(a.embers, i + 100, t)
        out.sparks.push({ ...sp, op: sp.op * k })
      }
      out.sparkColor = a.embers.color
      out.sparkCore = a.embers.core || null
    }
    if (a.dim && k > 0) { out.dim = Math.max(out.dim, a.dim * k); out.dimColor = a.dimColor || null }
    if (a.rain && k > 0) out.rain = { ...a.rain, k, t: tMs }
  }
  return out
}
// 残像（motion.ghosts＝{ fromMs, toMs, lagMs, n, op }）：fromMs〜toMs のあいだ、lagMs ずつ前の姿勢でポーズの絵を薄く重ねる（振り抜いて飛び込む勢い）
//   { name, ms（その残像の時刻）, op }。そのときに出ていたポーズの絵だけ（部品の立ち絵には残像を出さない）。
//   g.rig＝部品の立ち絵にも残像を出す（ゼルギアスの突進・name は null）
export const illustGhostsAt = (motion, ms) => {
  const g = motion?.ghosts
  if (!g || ms < g.fromMs || ms >= g.toMs) return []
  const out = []
  for (let k = 1; k <= g.n; k++) {
    const t = ms - g.lagMs * k
    if (t < g.fromMs - g.lagMs) break
    const top = illustShowAt(motion, t).poses.at(-1)
    if (top || g.rig) out.push({ name: top?.name ?? null, ms: t, op: (g.op ?? 0.45) * (1 - k / (g.n + 1)) })
  }
  return out
}
