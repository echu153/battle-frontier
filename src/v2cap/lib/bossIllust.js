//   art＝bossIllustOf の答え・name＝バフの名前・ms＝付いてからのミリ秒 → { rig, pose（ポーズの絵の濃さ）, aura: { op, scale } | null, flash（0〜1） } か null（その名前の絵が無い・時間の外）
