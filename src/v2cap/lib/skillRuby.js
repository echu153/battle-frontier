export const SKILL_RUBY = {
  // 黒龍ヴァルゼノク
  '黒爪': '｜黒爪《こくそう》',
  '焦熱の吐息': '｜焦熱《しょうねつ》の｜吐息《といき》',
  '黒翼烈風': '｜黒翼《こくよく》｜烈風《れっぷう》',
  '終焉の黒焔': '｜終焉《しゅうえん》の｜黒焔《こくえん》',
  '黒鱗の鎧': '｜黒鱗《こくりん》の｜鎧《よろい》',     // HP60%のバフ
  '逆鱗': '｜逆鱗《げきりん》',                       // HP30%のバフ
  // 雨摩座
  '雨礫': '｜雨礫《あまつぶて》',
  '氷雨': '｜氷雨《ひさめ》',
  '水縛の帯': '｜水縛《すいばく》の｜帯《おび》',
  '水天葬': '｜水天葬《すいてんそう》',
  '霧雨の帳': '｜霧雨《きりさめ》の｜帳《とばり》',     // HP60%のバフ
  '篠突く雨': '｜篠突《しのつ》く｜雨《あめ》',         // HP30%のバフ
}

// 技の名前 → [{ text, ruby? }]（ルビの無い名前はそのまま1つ）
export const rubySegmentsOf = (name) => {
  const src = SKILL_RUBY[name]
  if (!src) return [{ text: name }]
  const out = []
  const re = /｜([^《]+)《([^》]+)》|([^｜]+)/g
  for (let m; (m = re.exec(src));) out.push(m[3] ? { text: m[3] } : { text: m[1], ruby: m[2] })
  return out
}
