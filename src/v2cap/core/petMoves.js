// ------------------------------------------------------------
// 種ごとの「覚える技」は petSpecies.js が組み立てる。ここは技そのものの表。
//
// ⚠ **よそのゲームの技名をそのまま使わないこと**（2026-08-29 ユーザー指摘）。
//   最初「たいあたり」「かえんほうしゃ」のように他所の名前をそのまま置いていた。
//   名前も威力も、このゲームのものとして作り直してある。
//   足すときも、思いついた名前が他所のものでないか必ず確かめる。
//
// ★名前は**漢字だけにしない**（2026-09-03 ユーザー指摘）。
//   独・伊・西・羅・仏・英をカタカナにしたものを混ぜる。
//   「全部漢字」は見た目が単調で、どのタイプの技かも読み取りにくかった。
//
//   type … 技のタイプ（petTypes.js）
//   kind … 物理＝STRで殴る／特殊＝INTで撃つ／変化＝ダメージなし
//   pow  … 威力（変化技は0）。**覚えるLVはこの値から決まる**
//   acc  … 命中率(%)。100は必中ではなく「基本は当たる」
//   pp   … 1戦闘で使える回数
//   eff  … 追加効果。battle側（petBattle.js）が読む
//
// 追加効果の種類
//   burn/para/poison … そのまま残る状態（確率 chance）。1体に1つだけ
//   ail              … **本編と同じ状態異常**（petBattle.js の PET_AIL）。
//                       { key, pct, turns?, stacks? }。turns で消える＝重ねて持てる
//   up/up2/down      … ステの上げ下げ { stat, n }。up は自分・down は相手
//   downSelf         … 撃った自分のステが下がる（強い技の代償）
//   crit             … 急所に当たりやすい
//   drain            … 与えたダメージの半分だけ回復
//   heal             … 最大HPの割合だけ回復
//   multi            … 2〜5回当たる
//   priority         … 先に動く
//   recoil           … 与えたダメージの1/3を自分も受ける
//   chance           … up を「攻撃技のおまけ」として出すときの確率(%)
// ============================================================

