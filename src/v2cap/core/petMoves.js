// ============================================================
// 効果を一行の文にする
// ------------------------------------------------------------
// ★技が216個になって、名前だけでは何をするのか分からなくなった。
//   技を選ぶ画面と名鑑で**同じ文**を出すため、ここに1か所だけ置く
// ============================================================
export const AIL_TEXT = {
  bleed: '出血', blind: '暗闇', curse: '呪い', frenzy: '狂乱',
  weaken: '衰弱', slow: '鈍足', silence: 'サイレンス',
}
const STAT_TEXT = { str:'STR', int_stat:'INT', vit:'VIT', dex:'DEX', agi:'AGI', luk:'LUK' }
const upDown = (o, sign) => `${sign === '+' ? '自分' : '相手'}の${STAT_TEXT[o.stat] || o.stat}${sign}${o.n}`

export const moveEffText = (m) => {
  const e = m?.eff
  if (!e) return ''
  const out = []
  if (e.ail) out.push(`${AIL_TEXT[e.ail.key] || e.ail.key}${e.ail.pct < 100 ? ` ${e.ail.pct}%` : ''}`)
  if (e.burn) out.push(`やけど ${e.burn}%`)
  if (e.para) out.push(`まひ ${e.para}%`)
  if (e.poison) out.push(`どく ${e.poison}%`)
  if (e.up) out.push(upDown(e.up, '+') + (e.chance ? ` ${e.chance}%` : ''))
  if (e.up2) out.push(upDown(e.up2, '+'))
  if (e.down) out.push(upDown(e.down, '-'))
  if (e.downSelf) out.push(`代償：自分の${STAT_TEXT[e.downSelf.stat] || e.downSelf.stat}-${e.downSelf.n}`)
  if (e.heal) out.push(`HP${Math.round(e.heal * 100)}%回復`)
  if (e.drain) out.push('与えたダメージの半分を吸収')
  if (e.recoil) out.push('反動を受ける')
  if (e.multi) out.push('2〜5回当たる')
  if (e.priority) out.push('先に動く')
  if (e.crit) out.push('急所に当たりやすい')
  return out.join('・')
}
