//   名前も威力も、このゲームのものとして作り直してある。
//   足すときも、思いついた名前が他所のものでないか必ず確かめる。
//
//   type … 技のタイプ（petTypes.js）
//   kind … 物理＝STRで殴る／特殊＝INTで撃つ／変化＝ダメージなし
//   pow  … 威力（変化技は0）。**覚えるLVはこの値から決まる**
//   acc  … 命中率(%)。100は必中ではなく「基本は当たる」
//   pp   … 1戦闘で使える回数
//   eff  … 追加効果。battle側（petBattle.js）が読む
//
// 追加効果の種類
//   burn/para/poison … 状態異常（確率 chance）
//   up/down          … ステの上げ下げ { stat, n }
//   crit             … 急所に当たりやすい
//   drain            … 与えたダメージの半分だけ回復
//   heal             … 最大HPの割合だけ回復
//   multi            … 2〜5回当たる
//   priority         … 先に動く
//   recoil           … 与えたダメージの1/3を自分も受ける
// ============================================================

