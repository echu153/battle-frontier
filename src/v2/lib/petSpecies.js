// ============================================================
// 種族値
// ------------------------------------------------------------
// 役割ごとの配分 × 段階ごとの総量。同じ役割でも id ごとに少しずらす
// （±6・乱数ではなく id から作るので毎回同じ）
// ============================================================
export const STAT_ORDER = ['str', 'int_stat', 'vit', 'dex', 'agi', 'luk']

const SHARE = {
  atk: { str:30, int_stat:10, vit:18, dex:16, agi:18, luk:8 },
  mag: { str:10, int_stat:30, vit:17, dex:17, agi:18, luk:8 },
  def: { str:18, int_stat:14, vit:32, dex:14, agi:12, luk:10 },
  spd: { str:18, int_stat:16, vit:12, dex:18, agi:30, luk:6 },
  bal: { str:18, int_stat:18, vit:18, dex:16, agi:18, luk:12 },
}

// 段階ごとの総量。★進化しない種（solo）は1段目よりずっと高く、
//   最終進化よりは少し低い＝「進化しないけどそこそこ強い」
const TOTAL = { first: 300, mid: 400, last: 560, second: 440, solo: 470, legend: 600 }

// id から作る小さなブレ（-6〜+6）
const jitter = (id, i) => ((id * 37 + i * 101) % 13) - 6

const baseStatsOf = (id, role, stageKey) => {
  const share = SHARE[role]
  const total = TOTAL[stageKey]
  const out = {}
  STAT_ORDER.forEach((k, i) => {
    out[k] = Math.max(10, Math.round(total * share[k] / 100) + jitter(id, i))
  })
  return out
}

// 合計をぴったり want に合わせる。ズレは役割の主ステで吸わせる
// （伝説の「種族値600」をきっちり見せるため）
const MAIN_OF = { atk:'str', mag:'int_stat', def:'vit', spd:'agi', bal:'str' }
const exactTotal = (base, want, role) => {
  const out = { ...base }
  const now = STAT_ORDER.reduce((t, k) => t + out[k], 0)
  const k = MAIN_OF[role] || 'str'
  out[k] = Math.max(10, out[k] + (want - now))
  return out
}

// ============================================================
// 覚える技
// ------------------------------------------------------------
// 自分のタイプの技を弱いものから順に、無タイプの基本技・補助技を混ぜて並べる。
// ★同じタイプでも役割と段階でぜんぶ変わる＝種ごとに覚える技が違う
// ============================================================
const NEUTRAL_START = { atk:'小突き', mag:'思念弾', def:'小突き', spd:'爪牙', bal:'小突き' }
const NEUTRAL_UTIL = {
  atk:['威圧', '研ぎ澄まし', '重圧撃'],
  mag:['目つぶし', '養生', '衝波'],
  def:['構え直し', '養生', '重圧撃'],
  spd:['疾駆', '機先', '乱撃'],
  bal:['威圧', '養生', '重圧撃'],
}
// 役割ごとに、どちらの技を優先して覚えるか
const PREFER = { atk:'物理', mag:'特殊', def:'物理', spd:'物理', bal:null }

// ★覚えるLVは**技の威力から決める**。順番に並べるだけだと、
//   自タイプの弱い技が少ない種（炎の物理技は2つしかない等）で
//   威力120の技をLV5で覚えてしまう（実際そうなっていた）
// 熾天使の専用技の名前。ふつうの種が拾わないようにここで弾く
const SIG_MOVES = new Set(LEGENDS.map(l => l.sig))

const lvForPower = (pow) =>
  (pow <= 45 ? 1 : pow <= 60 ? 7 : pow <= 75 ? 14 : pow <= 90 ? 22 : pow <= 110 ? 32 : 42)

// 段階ごとに覚えられる威力の上限。1段目のうちから大技は覚えない
const POW_CAP = { 0: 90, 1: 110, 2: 999 }

// ★技を増やした（78→188）ので、**タイプの技を全部覚えさせない**。
//   全部だと1種が25技も覚えて、どの種も同じ顔になってしまう。
//   種ごとに違う組み合わせを、乱数を使わず**idから決める**。
export const ATTACK_PICKS = 7      // 攻撃技をいくつ覚えるか
export const CHANGE_PICKS = 3      // 変化技をいくつ覚えるか

// 並んだ候補から n 個を「散らして」選ぶ。offset を変えると別の顔になる
const pickSpread = (list, n, offset) => {
  if (list.length <= n) return list.slice()
  const out = []
  const used = new Set()
  for (let i = 0; i < n; i++) {
    // 端から端まで等間隔に取り、offset で少しずらす
    let at = Math.round(i * (list.length - 1) / (n - 1)) + (i === 0 || i === n - 1 ? 0 : offset % 2)
    at = Math.max(0, Math.min(list.length - 1, at))
    while (used.has(at)) at = (at + 1) % list.length
    used.add(at)
    out.push(list[at])
  }
  return out.sort((a, b) => list.indexOf(a) - list.indexOf(b))
}

export const learnsetOf = (sp) => {
  const prefer = PREFER[sp.role]
  const cap = POW_CAP[Math.min(sp.stage, 2)] ?? 999
  // 進化しない種（1体だけの家系）は最初から最終進化ぶんを覚える
  const powCap = sp.stages === 1 ? 999 : cap

  const seen = new Set()
  const pool = []
  for (const t of sp.types) {
    for (const m of MOVES.filter(x => x.type === t)) {
      if (seen.has(m.name)) continue
      // ★専用技はここでは配らない（持ち主にだけ、下でLV50に置く）
      if (SIG_MOVES.has(m.name)) continue
      if (m.kind !== '変化' && m.pow > powCap) continue
      seen.add(m.name)
      pool.push(m)
    }
  }
  // 威力の低い順。同じくらいなら役割に合うほうを先に（変化技は中盤に置く）
  const keyOf = (m) => (m.kind === '変化' ? 62 : m.pow - (m.kind === prefer ? 8 : 0))
  pool.sort((a, b) => keyOf(a) - keyOf(b))

  // 攻撃技と変化技を分けて選ぶ。分けないと、変化技ばかりの種が出てしまう
  const atk = pool.filter(m => m.kind !== '変化')
  const chg = pool.filter(m => m.kind === '変化')
  // ★家系の中で覚える技が同じにならないよう、id で選び方をずらす
  const off = sp.id % 3
  const typed = [
    ...pickSpread(atk, ATTACK_PICKS, off),
    ...pickSpread(chg, CHANGE_PICKS, off + 1),
  ]
  // いちばん強い技（そのタイプ・その段階で覚えられるもの）は必ず入れる
  const top = atk[atk.length - 1]
  if (top && !typed.includes(top)) typed.push(top)
  typed.sort((a, b) => keyOf(a) - keyOf(b))

  const out = [{ lv: 1, move: NEUTRAL_START[sp.role] }]
  const put = (name, lv) => {
    if (!name || !MOVE_BY_NAME[name] || out.some(e => e.move === name)) return
    // 同じLVに固まらないよう2ずつずらす
    let at = Math.max(1, lv)
    while (out.some(e => e.lv === at)) at += 2
    out.push({ lv: at, move: name })
  }

  for (const m of typed) put(m.name, m.kind === '変化' ? 10 : lvForPower(m.pow))
  // 無タイプの補助技。役割ごとに違うものが入る
  NEUTRAL_UTIL[sp.role].forEach((name, i) => put(name, 12 + i * 11))
  // 熾天使の専用技。★終盤で覚える（威力125以上なので LV50）
  if (sp.sig) put(sp.sig, 50)

  return out.sort((a, b) => a.lv - b.lv)
}

// そのLVまでに覚えている技
export const knownMoves = (sp, lv) =>
  learnsetOf(sp).filter(e => e.lv <= lv).map(e => e.move)

