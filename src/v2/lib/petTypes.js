// ------------------------------------------------------------
// ★本編（v2の戦闘）の属性とは別立て。ペットのバトルは
//   「この相手にはこの子」を選ぶ遊びにしたいので、
//   見ただけで分かる12タイプ＋2倍/半減だけにしてある。
//
//   無 … どのタイプにも等倍。序盤の技と、色のない種のためのタイプ
// ============================================================

export const PET_TYPES = [
  { key:'無', color:'#a8b4c4' },
  { key:'炎', color:'#ff6644' },
  { key:'水', color:'#44aaff' },
  { key:'草', color:'#44cc66' },
  { key:'雷', color:'#ffdd44' },
  { key:'氷', color:'#88e0ff' },
  { key:'地', color:'#c8a060' },
  { key:'風', color:'#88ffcc' },
  { key:'岩', color:'#b09070' },
  { key:'毒', color:'#cc66ee' },
  { key:'闇', color:'#8877bb' },
  { key:'光', color:'#ffe9a0' },
  { key:'鋼', color:'#a0b0c0' },
]
export const TYPE_KEYS = PET_TYPES.map(t => t.key)
export const TYPE_COLOR = Object.fromEntries(PET_TYPES.map(t => [t.key, t.color]))

// 攻撃タイプ → { 相手タイプ: 倍率 }。書いていない組み合わせは等倍
const CHART = {
  炎: { 草:2, 氷:2, 鋼:2, 水:0.5, 岩:0.5, 地:0.5, 炎:0.5 },
  水: { 炎:2, 岩:2, 地:2, 草:0.5, 雷:0.5, 水:0.5 },
  草: { 水:2, 岩:2, 地:2, 炎:0.5, 氷:0.5, 毒:0.5, 風:0.5, 草:0.5, 鋼:0.5 },
  雷: { 水:2, 風:2, 地:0.5, 草:0.5, 雷:0.5 },
  氷: { 草:2, 地:2, 風:2, 炎:0.5, 鋼:0.5, 氷:0.5 },
  地: { 炎:2, 雷:2, 毒:2, 岩:2, 鋼:2, 水:0.5, 草:0.5, 風:0.5 },
  風: { 草:2, 毒:2, 雷:0.5, 氷:0.5, 岩:0.5, 鋼:0.5 },
  岩: { 炎:2, 氷:2, 風:2, 水:0.5, 草:0.5, 地:0.5, 鋼:0.5 },
  毒: { 草:2, 光:2, 地:0.5, 岩:0.5, 毒:0.5, 鋼:0.5 },
  闇: { 光:2, 毒:0.5, 闇:0.5, 鋼:0.5 },
  光: { 闇:2, 毒:2, 光:0.5, 鋼:0.5 },
  鋼: { 氷:2, 岩:2, 光:2, 炎:0.5, 水:0.5, 雷:0.5, 鋼:0.5 },
}

// 技のタイプ atk が、相手のタイプたち def に何倍になるか。
// ★2タイプ持ちは掛け算（4倍・1/4倍まで出る）
export const typeMult = (atk, defTypes) => {
  const row = CHART[atk]
  if (!row) return 1
  return (defTypes || []).reduce((m, d) => m * (row[d] ?? 1), 1)
}

// 効果の言い方。バトルログに出す
export const typeText = (mult) => {
  if (mult === 0) return '効果がない'
  if (mult >= 4) return '効果は絶大だ'
  if (mult > 1) return '効果は抜群だ'
  if (mult <= 0.25) return 'ほとんど効かない'
  if (mult < 1) return '効果はいまひとつだ'
  return ''
}

// そのタイプが得意な相手／苦手な相手（図鑑の表示用）
export const strongAgainst = (t) =>
  TYPE_KEYS.filter(d => typeMult(t, [d]) > 1)
export const weakAgainst = (t) =>
  TYPE_KEYS.filter(a => typeMult(a, [t]) > 1)
